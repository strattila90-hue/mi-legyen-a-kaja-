var SPC={};
function spr(name,cls){
  if(SPC[name+"|"+(cls||"")])return SPC[name+"|"+(cls||"")];
  var g=SPR[name]||SPR.jar,o="";
  for(var y=0;y<g.length;y++){var row=g[y],x=0;
    while(x<row.length){var ch=row[x];if(ch==="."){x++;continue}
      var s=x;while(x<row.length&&row[x]===ch)x++;
      o+='<rect x="'+s+'" y="'+y+'" width="'+(x-s)+'" height="1" fill="'+PAL[ch]+'"/>'}}
  return SPC[name+"|"+(cls||"")]='<svg class="px'+(cls?" "+cls:"")+'" viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">'+o+"</svg>";
}
